#!/usr/bin/env python3
"""Process-symbol compression measurement (smoke test).

Question: which process-type compacts the corpus's mechanisms most
efficiently, measured as conclusions preserved per wire token?

Method (upper-bound / feasibility):
  - 6 mechanism-bearing entities from exp2_registry_v2.json.
  - Baseline wire: label + aliases + notes as literal text (v6 style).
  - Process wire: hand-written OPCODE(params => consequence-tags @status).
    Tags name conclusions; content must be regenerated by the interpreter.
    Status qualifiers ride a 1-token status tag (v6 status channel).
  - Token count: BPE proxy = words + punctuation marks.
  - Each conclusion judged: P=stored as parameter, Y=regenerated by
    interpreter, A=asserted in symbol (not derivable), S=status tag.
  - Honest framing: hand-encoded => UPPER BOUND on achievable compression;
    the interpreter here is the experimenter. Tests feasibility, not a
    running system.
"""
import json, re

def tok(s):
    return len(re.findall(r"\w+|[^\w\s]", s))

ents = {e['entity_id']: e for e in
        json.load(open('corpus_runs/exp2_registry_v2.json'))}

def baseline(e):
    return ' '.join([e['label']] + e.get('aliases', []) + e.get('notes', []))

# opcode, process-string, conclusions[(name, kind, how)]
MECHS = [
 ("E017", "ITER",
  "ITER(R_p={0},{0,-2} => twin-lowers mu-id delta(z) 2C2 @conjectural-tail)",
  [("deformation rule R_p", "mech", "P"),
   ("survivors = twin lowers (2160 <=2e5)", "mech", "Y"),
   ("deformed mu-identity exact", "mech", "Y"),
   ("face multiplicities, delta(z) formulas", "mech", "Y"),
   ("S(z)->2C2=1.32032 + z-table", "mech", "Y"),
   ("twin conjecture itself unproven", "status", "S")]),
 ("E023", "ITER",
  "ITER(phi(x,a)=phi(x,a-1)-phi(x/p_a,a-1) => face-sum-D1 ~=soft-limit[2405.09608] @conceptual)",
  [("two-term split rule, exact", "mech", "P"),
   ("iteration to all orders = D1 face-sum", "mech", "Y"),
   ("identification with soft-limit move", "mech", "A"),
   ("mapping is conceptual not theorem", "status", "S")]),
 ("E152", "PIPE",
  "PIPE(EulerProds->D_log->zero-match => eq42@2e-16 bugfix-k13 @secondary)",
  [("built from prime Euler products", "mech", "P"),
   ("eq.(4.2),(weinfty) verified to 2e-16", "mech", "Y"),
   ("k=13 bug found and fixed", "mech", "A"),
   ("construct is secondary/unverified", "status", "S")]),
 ("E049", "BRIDGE",
  "BRIDGE(psi-primes|sum x^rho/rho-zeros via Davenport => trunc-approx err-decay(T) @theorem)",
  [("explicit formula psi(x)=x-sum x^rho/rho-...", "mech", "P"),
   ("truncated zero sum reproduces psi oscillations", "mech", "Y"),
   ("error decays with T (4.55->1.3)", "mech", "Y"),
   ("classical exact theorem", "status", "S")]),
 ("E000", "INVERT",
  "INVERT(face-sum by Moebius => prime-counts bijection-exact @verified)",
  [("faces = finite prime subsets", "mech", "P"),
   ("face-sum Moebius inversion recovers counts", "mech", "Y"),
   ("link-face counts match, bijection exact", "mech", "Y"),
   ("corrected sieve = classical primes", "mech", "Y")]),
 ("E057", "BRIDGE",
  "BRIDGE(Weil|H|^2|autocorr|Q|^2 via squaring => positivity-both @exact)",
  [("dictionary Weil h=|H|^2 <-> P=|Q|^2", "mech", "P"),
   ("translation is exact", "mech", "A"),
   ("same generative squaring move both sides", "mech", "Y"),
   ("exact (status)", "status", "S")]),
]

rows = []
for eid, op, proc, concls in MECHS:
    e = ents[eid]
    b = baseline(e)
    tb, tp = tok(b), tok(proc)
    n = len(concls)
    y = sum(1 for _, _, h in concls if h == "Y")
    nonparam = [h for _, _, h in concls if h != "P"]
    regen_frac = sum(1 for h in nonparam if h == "Y") / len(nonparam)
    rows.append(dict(eid=eid, op=op, tb=tb, tp=tp, ratio=tb / tp,
                     n=n, cpt_base=n / tb, cpt_proc=n / tp,
                     regen_frac=regen_frac, proc=proc))

print(f"{'eid':6} {'op':7} {'t_base':>7} {'t_proc':>7} {'ratio':>6} "
      f"{'concl':>6} {'c/tok_b':>8} {'c/tok_p':>8} {'regen%':>7}")
for r in rows:
    print(f"{r['eid']:6} {r['op']:7} {r['tb']:7} {r['tp']:7} "
          f"{r['ratio']:6.2f} {r['n']:6} {r['cpt_base']:8.3f} "
          f"{r['cpt_proc']:8.3f} {r['regen_frac']:7.0%}")

json.dump(rows, open("corpus_runs/exp2_procsym_rows.json", "w"), indent=1)

# per-opcode aggregates
from collections import defaultdict
agg = defaultdict(lambda: [0, 0, 0, 0])  # tb, tp, n, uses
for r in rows:
    a = agg[r["op"]]
    a[0] += r["tb"]; a[1] += r["tp"]; a[2] += r["n"]; a[3] += 1
print("\nper-opcode:")
for op, (tb, tp, n, u) in agg.items():
    print(f"  {op:7} uses={u} tokratio={tb/tp:.2f} c/tok: base={n/tb:.3f} proc={n/tp:.3f}")
tb_tot = sum(r["tb"] for r in rows); tp_tot = sum(r["tp"] for r in rows)
n_tot = sum(r["n"] for r in rows)
print(f"\nTOTAL: base {tb_tot} tok, proc {tp_tot} tok, ratio {tb_tot/tp_tot:.2f}x; "
      f"c/tok {n_tot/tb_tot:.3f} -> {n_tot/tp_tot:.3f}")
